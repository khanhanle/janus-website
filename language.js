const LANG_KEY = "janus-lang";

function getLang() {
  const saved = localStorage.getItem(LANG_KEY);
  return saved === "vn" || saved === "en" ? saved : "en";
}

function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang);
  document.documentElement.lang = lang === "vn" ? "vi" : "en";

  const dict = translations[lang];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key] != null) el.setAttribute("placeholder", dict[key]);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (dict[key] == null) return;
    el.setAttribute("aria-label", dict[key]);
    if (el.tagName === "IMG") el.setAttribute("alt", dict[key]);
  });

  const pageKey = document.body.getAttribute("data-page-title");
  if (pageKey && dict[pageKey]) document.title = dict[pageKey];

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.getAttribute("data-lang") === lang;
    btn.classList.toggle("is-active", active);
    btn.setAttribute("aria-pressed", active ? "true" : "false");
  });
}

function initI18n() {
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => setLang(btn.getAttribute("data-lang")));
  });
  setLang(getLang());
}

document.addEventListener("DOMContentLoaded", initI18n);
